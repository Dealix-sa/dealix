"""Negotiation Intelligence Engine for Company Intelligence.

Provides tactical intelligence for deal negotiation: assessing positions,
recommending moves, evaluating counter-offers, and tracking concessions.
Uses NegotiationStrategy contracts to enforce boundaries and approach.

This engine NEVER makes commitments. It produces assessments and
recommendations that flow through the Action → Approval chain.
All pricing/scope commitments require human approval.

The engine is persistence-neutral: no database, network, or LLM calls.

Entity ownership:
    Uses NegotiationStrategy (deal_intelligence) contracts.
    Produces inputs for Action (action_queue) and Draft (draft_generation).
"""
from __future__ import annotations

import json
from datetime import UTC, datetime
from enum import StrEnum
from hashlib import sha256
from typing import Annotated, Any

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    StringConstraints,
    model_validator,
)

from dealix.company_intelligence.negotiation_contracts import (
    CanonicalNegotiationStrategy,
    NegotiationBoundary,
    NegotiationBoundaryType,
    NegotiationStage,
)

NonEmptyString = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1)]


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------


class MoveType(StrEnum):
    """Types of tactical moves in a negotiation."""

    ANCHOR = "anchor"
    CONCEDE = "concede"
    HOLD_FIRM = "hold_firm"
    COUNTER = "counter"
    REFRAME = "reframe"
    ADD_VALUE = "add_value"
    ESCALATE = "escalate"
    CLOSE = "close"
    WALK_AWAY = "walk_away"
    PAUSE = "pause"


class BoundaryStatus(StrEnum):
    """Result of checking a position against strategy boundaries."""

    WITHIN = "within"
    SOFT_WARNING = "soft_warning"
    HARD_VIOLATION = "hard_violation"


class PositionStrength(StrEnum):
    """Relative strength of the negotiation position."""

    STRONG = "strong"
    MODERATE = "moderate"
    WEAK = "weak"
    CRITICAL = "critical"


# ---------------------------------------------------------------------------
# Stable IDs
# ---------------------------------------------------------------------------


def _stable_assessment_id(payload: dict[str, Any]) -> str:
    canonical = json.dumps(
        payload,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
        default=str,
    )
    return f"negassess_{sha256(canonical.encode('utf-8')).hexdigest()[:16]}"


def _stable_move_id(payload: dict[str, Any]) -> str:
    canonical = json.dumps(
        payload,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
        default=str,
    )
    return f"negmove_{sha256(canonical.encode('utf-8')).hexdigest()[:16]}"


# ---------------------------------------------------------------------------
# Boundary Check Result
# ---------------------------------------------------------------------------


class BoundaryCheckResult(BaseModel):
    """Result of checking a value against a negotiation boundary.

    Captures which boundary was checked, whether it was violated, and
    whether the violation is a hard stop or a soft warning.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    boundary: NegotiationBoundary
    status: BoundaryStatus
    current_value: str = ""
    message: str = ""


# ---------------------------------------------------------------------------
# Negotiation Assessment — snapshot of position
# ---------------------------------------------------------------------------


class NegotiationAssessment(BaseModel):
    """A point-in-time assessment of a negotiation's position.

    Assessments are generated by the Negotiation Engine to help the
    human approver understand the current state of a deal and make
    informed decisions.

    Key invariants:
        - assessment_id is deterministic.
        - requires_human_decision is always True for recommendations
          involving commitments.
        - boundary_violations trigger automatic escalation.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    # Identity
    tenant_id: NonEmptyString
    assessment_id: NonEmptyString
    strategy_id: NonEmptyString
    opportunity_id: NonEmptyString

    # Position analysis
    current_stage: NegotiationStage
    position_strength: PositionStrength
    win_probability: float = Field(default=0.0, ge=0.0, le=1.0)

    # Boundary status
    boundary_checks: tuple[BoundaryCheckResult, ...] = ()
    has_hard_violations: bool = False
    has_soft_warnings: bool = False

    # Concession tracking
    concessions_made: tuple[str, ...] = ()
    concessions_remaining: tuple[str, ...] = ()
    total_concession_value_pct: float = Field(default=0.0, ge=0.0, le=1.0)

    # Scoring
    leverage_score: float = Field(default=0.5, ge=0.0, le=1.0)
    urgency_score: float = Field(default=0.5, ge=0.0, le=1.0)

    # Decision support
    key_risks: tuple[str, ...] = ()
    key_advantages: tuple[str, ...] = ()
    requires_human_decision: bool = True

    # Provenance
    source_id: NonEmptyString
    assessed_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @model_validator(mode="after")
    def enforce_assessment_invariants(self) -> NegotiationAssessment:
        # Hard violations must be flagged
        hard_checks = [
            c for c in self.boundary_checks
            if c.status == BoundaryStatus.HARD_VIOLATION
        ]
        if hard_checks and not self.has_hard_violations:
            raise ValueError(
                "assessment has hard boundary violations but "
                "has_hard_violations is False"
            )

        # Soft warnings must be flagged
        soft_checks = [
            c for c in self.boundary_checks
            if c.status == BoundaryStatus.SOFT_WARNING
        ]
        if soft_checks and not self.has_soft_warnings:
            raise ValueError(
                "assessment has soft boundary warnings but "
                "has_soft_warnings is False"
            )

        # Verify deterministic ID
        expected_id = _stable_assessment_id({
            "opportunity_id": self.opportunity_id,
            "strategy_id": self.strategy_id,
            "tenant_id": self.tenant_id,
        })
        if self.assessment_id != expected_id:
            raise ValueError(
                "assessment_id does not match the canonical payload"
            )

        return self


# ---------------------------------------------------------------------------
# Recommended Move — what to do next
# ---------------------------------------------------------------------------


class RecommendedMove(BaseModel):
    """A tactical recommendation for the next negotiation action.

    RecommendedMoves are suggestions — never commitments. They require
    human approval before any external action is taken.

    Key invariants:
        - approval_required is always True.
        - execution_allowed is always False.
        - move_id is deterministic.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    # Identity
    tenant_id: NonEmptyString
    move_id: NonEmptyString
    assessment_id: NonEmptyString
    strategy_id: NonEmptyString

    # Move details
    move_type: MoveType
    description: NonEmptyString
    rationale: NonEmptyString

    # Talking points
    talking_points: tuple[str, ...] = ()
    objection_responses: tuple[tuple[str, str], ...] = ()

    # Value framing
    value_proposition: str = ""
    concession_offered: str = ""
    concession_requested: str = ""

    # Risk assessment
    risk_if_taken: str = ""
    risk_if_not_taken: str = ""
    confidence: float = Field(default=0.5, ge=0.0, le=1.0)

    # Safety — ALWAYS
    approval_required: bool = True
    execution_allowed: bool = False

    # Provenance
    source_id: NonEmptyString
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @model_validator(mode="after")
    def enforce_move_invariants(self) -> RecommendedMove:
        if not self.approval_required:
            raise ValueError(
                "recommended moves always require approval"
            )
        if self.execution_allowed:
            raise ValueError(
                "recommended moves never authorize execution"
            )

        expected_id = _stable_move_id({
            "assessment_id": self.assessment_id,
            "move_type": self.move_type.value,
            "strategy_id": self.strategy_id,
            "tenant_id": self.tenant_id,
        })
        if self.move_id != expected_id:
            raise ValueError(
                "move_id does not match the canonical payload"
            )

        return self


